"""Narration with the expressive voice model (Chatterbox, cloned from the channel's reference voice).

usage: python3 audio/narrate_cb.py scenarios/<id>.vo.json

The spec is like narrate.py's, plus:
  "engine": "chatterbox", "ref": "/home/user/tts/ref/voice.wav", "tempo": 1.08,
  "exaggeration": 0.5, "cfg": 0.5, "temperature": 0.7
Chatterbox runs in its own Python 3.11 venv (/home/user/tts/.venv, see setup notes in PLAYBOOK.md); this script calls it per
line, then trims, speeds up (pitch kept), levels, transcribes every line with Whisper and keeps a take only when the words
match the script (otherwise it tries another seed). Writes assets/vo/<id>/<key>.wav and scenarios/<id>.vo.js with word timings.
"""
import os, sys, json, subprocess, difflib, re
import numpy as np, soundfile as sf
from scipy.signal import resample_poly

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'audio'))
from narrate import trim, level, script_words  # noqa: E402

VENV = '/home/user/tts/.venv/bin/python'
GEN = '/home/user/tts/cb.py'
norm = lambda s: re.sub(r'[^a-z0-9 ]', '', s.lower().replace('-', ' ')).split()


def squeeze(a, sr, maxgap=0.38, keep=0.3):
    """Shorten every pause longer than maxgap seconds to `keep` seconds (natural rhythm, no dead air)."""
    hop = int(0.01 * sr); n = len(a) // hop
    db = 20 * np.log10(np.sqrt(np.mean(a[:n * hop].reshape(n, hop) ** 2, axis=1)) + 1e-9)
    quiet = db < (db.max() - 38)
    out, i, last = [], 0, 0
    while i < n:
        if quiet[i]:
            j = i
            while j < n and quiet[j]: j += 1
            if (j - i) * 0.01 > maxgap:
                cut0, cut1 = (i + int(keep / 2 / 0.01)) * hop, (j - int(keep / 2 / 0.01)) * hop
                out.append(a[last:cut0]); last = cut1
            i = j
        else:
            i += 1
    out.append(a[last:])
    return np.concatenate(out)


def main():
    spec = json.load(open(sys.argv[1]))
    vid = spec['id']
    raw = os.path.join(ROOT, 'assets', 'vo', vid + '-raw'); os.makedirs(raw, exist_ok=True)
    out = os.path.join(ROOT, 'assets', 'vo', vid); os.makedirs(out, exist_ok=True)
    from faster_whisper import WhisperModel
    stt = WhisperModel('small.en', device='cpu', compute_type='int8')
    env = dict(os.environ, EXAG=str(spec.get('exaggeration', 0.5)), CFG=str(spec.get('cfg', 0.5)), TEMP=str(spec.get('temperature', 0.7)))
    result = {}
    for key, line in spec['lines'].items():
        text = line if isinstance(line, str) else line['say']
        best = None
        for attempt in range(4):
            wav = os.path.join(raw, f'{key}-{attempt}.wav')
            if not os.path.exists(wav):
                subprocess.run([VENV, GEN, spec['ref'], raw, f'{key}-{attempt}={text}'], env=dict(env, SEED=str(7 + attempt * 13)),
                               check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            # trim, speed up with the pitch kept, level
            tmp = os.path.join(raw, f'{key}-{attempt}-fast.wav')
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', wav, '-af', f"atempo={spec.get('tempo', 1.08)}", '-ar', '24000', '-ac', '1', tmp], check=True)
            a, sr = sf.read(tmp)
            audio = level(squeeze(trim(np.asarray(a, dtype=np.float64), sr), sr, spec.get('maxgap', 0.38), spec.get('gap', 0.3)))
            a16 = resample_poly(audio, 2, 3).astype(np.float32)
            segs, _ = stt.transcribe(a16, word_timestamps=True)
            words = [[w.word.strip(), round(w.start, 3), round(w.end, 3)] for s in segs for w in s.words]
            heard = ' '.join(w[0] for w in words)
            score = difflib.SequenceMatcher(None, norm(heard), norm(text)).ratio()
            print(f'{key:8s} take {attempt}  {score:.2f}  {heard}', flush=True)
            if best is None or score > best[0]:
                best = (score, audio, sr, words)
            if score >= 0.93:
                break
        score, audio, sr, words = best
        sf.write(os.path.join(out, f'{key}.wav'), audio.astype(np.float32), sr)
        result[key] = {'file': f'vo/{vid}/{key}.wav', 'dur': round(len(audio) / sr, 3), 'text': text, 'words': script_words(words, text)}
    js = os.path.join(ROOT, 'scenarios', f'{vid}.vo.js')
    with open(js, 'w') as f:
        f.write('// generated by audio/narrate_cb.py — voice-over line lengths and word timings\n')
        f.write('export default ' + json.dumps(result, indent=1) + ';\n')
    print('wrote', js)


if __name__ == '__main__':
    main()
